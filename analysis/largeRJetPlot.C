// Plot stage of the largeRJetAnalysisAndRates split (largeRJetSplitPlan.md).
//
// Loads each configured pair's merged state file
//   /data/larsonma/LargeRadiusJets/largeRJetIntermediateState/<taggerBase>__state.root
// in place of running the two big background event loops, then does everything else the
// monolithic macro did — signal loops, threshold derivations, scans, turn-ons, every
// per-file and overlay PDF — with the identical code path.
//
// Usage (after the usual ATLAS env + lsetup root):
//   root -b -l -q 'largeRJetPlot.C'
//
// WORKFLOW: generate the pair list ONCE with
//     cd ../condor && python3 submit_largeRJetCompute.py --pairs-only        # all pairs
// and from then on choose what to plot by editing kPlotSelect below — the pair list does
// not need regenerating to change a study. Any subset/ordering works against
// already-computed state, because state files carry no pair index.
//
// Prerequisite: compute run and hadd'd for every SELECTED pair. A missing state file is a
// fatal error, as is a missing histogram inside one.
// Known plot-stage gap vs the monolith: the five background event-display PDFs
// (displayEv*Back_) are not produced — their per-event geometry only exists while the
// background loops run.
